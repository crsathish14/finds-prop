// Concatenates assets/js/*.js (in dependency order) into assets/fp.js, the single script every screen loads.
// Run after editing anything in assets/js:   node tools/build-js.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const order = ['fp-icons.js', 'fp-art.js', 'fp-data.js', 'fp-ui.js', 'fp-pages.js', 'fp-charts.js', 'fp-portal.js', 'fp-portal2.js'];
const out = order.map((f) => `/* ===== ${f} ===== */\n` + fs.readFileSync(path.join(root, 'assets', 'js', f), 'utf8')).join('\n');
fs.writeFileSync(path.join(root, 'assets', 'fp.js'), '/* Generated by tools/build-js.mjs from assets/js/*.js. Edit the sources, not this file. */\n' + out);
console.log(`assets/fp.js written (${out.length} bytes)`);
