// G-16 Harness integrity: the instruction files are the right size, and everything they mention
// (paths, npm scripts, rule IDs, gate IDs) exists. Also checks ADR numbering, skills and hooks.
// Usage: node scripts/check-harness.mjs
import fs from "node:fs";
import path from "node:path";
import { finding, isMain, listFiles, printFindings, readText, repoRoot } from "./lib/core.mjs";

const ROOT_LIMIT = 150;
const NESTED_LIMIT = 40;
const SKILL_LIMIT = 30;
const BEGIN = "<!-- BEGIN:nextjs-agent-rules -->";
const END = "<!-- END:nextjs-agent-rules -->";
const RUNTIME_ONLY = [
  /^\.next\//,
  /^node_modules\//,
  /^\.env\.local$/,
  /^\.claude\/settings\.local\.json$/,
  /^CLAUDE\.local\.md$/, // named in instructions precisely because it must not exist
];
const PATHISH = /\.(md|mjs|json|ts|tsx|sql|ya?ml|toml)$/;

function lineCount(text) {
  return text.replace(/\n$/, "").split("\n").length;
}

function stripNextBlock(text) {
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) return text;
  return text.slice(0, start) + text.slice(end + END.length);
}

function backtickSpans(text) {
  return [...text.matchAll(/`([^`\n]+)`/g)].map((m) => m[1]);
}

function looksLikeRepoPath(span) {
  if (/[\s<>*{}$…]|^https?:|^npm |^--|^@|^\.\.\./.test(span)) return false;
  if (/^[A-Z]{1,5}-\d+/.test(span)) return false;
  return span.includes("/")
    ? /^[\w./-]+$/.test(span)
    : PATHISH.test(span) && /^[\w.-]+$/.test(span);
}

export function checkHarness({ root = repoRoot, files = listFiles(root) } = {}) {
  const findings = [];
  const exists = (rel) => fs.existsSync(path.join(root, rel));
  const pkg = exists("package.json")
    ? JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"))
    : { scripts: {} };

  // --- instruction files
  const instructionFiles = files.filter(
    (f) =>
      f === "AGENTS.md" ||
      f.endsWith("/AGENTS.md") ||
      f === "CONTRIBUTING.md" ||
      /^\.claude\/skills\/[^/]+\/SKILL\.md$/.test(f),
  );
  if (!exists("AGENTS.md"))
    findings.push(
      finding(
        "AGENTS.md",
        0,
        "H-MISSING",
        "AGENTS.md is the single instruction source and must exist",
      ),
    );

  const handbook = files.filter((f) => /^docs\/engineering\/[^/]+\.md$/.test(f));
  const definedRules = new Map();
  const definedGates = new Set();
  for (const file of handbook) {
    const text = readText(root, file) ?? "";
    for (const m of text.matchAll(/^\|\s*(R-[A-Z]+-\d\d)\s*\|/gm)) {
      if (definedRules.has(m[1]))
        findings.push(
          finding(
            file,
            0,
            "H-RULE-DUP",
            `${m[1]} is defined here and in ${definedRules.get(m[1])}; each rule has one home`,
          ),
        );
      else definedRules.set(m[1], file);
    }
    for (const m of text.matchAll(/^\|\s*(G-\d\d)\s*\|/gm)) definedGates.add(m[1]);
  }

  for (const file of instructionFiles) {
    const raw = readText(root, file) ?? "";
    const text = stripNextBlock(raw);
    const lines = lineCount(text);
    const isRoot = file === "AGENTS.md";
    const isSkill = file.startsWith(".claude/skills/");
    const limit = isRoot
      ? ROOT_LIMIT
      : isSkill
        ? SKILL_LIMIT
        : file === "CONTRIBUTING.md"
          ? 20
          : NESTED_LIMIT;
    if (lines > limit)
      findings.push(
        finding(
          file,
          0,
          "H-SIZE",
          `${lines} lines; the limit is ${limit} (instruction files stay small, see docs/engineering/workflow.md)`,
        ),
      );

    if (isRoot) {
      const hasBegin = raw.includes(BEGIN);
      const hasEnd = raw.includes(END);
      if (hasBegin !== hasEnd || (hasBegin && raw.indexOf(END) < raw.indexOf(BEGIN)))
        findings.push(
          finding(
            file,
            0,
            "H-MARKERS",
            "the Next.js managed block markers are damaged; restore them (the block is generated by next dev)",
          ),
        );
    }

    for (const span of backtickSpans(text)) {
      const script = /^npm run ([\w:-]+)/.exec(span);
      if (script) {
        if (!pkg.scripts?.[script[1]])
          findings.push(
            finding(
              file,
              0,
              "H-SCRIPT",
              `mentions npm run ${script[1]} but package.json has no such script`,
            ),
          );
        continue;
      }
      if (!looksLikeRepoPath(span)) continue;
      if (RUNTIME_ONLY.some((re) => re.test(span))) continue;
      // a module specifier such as next/image: the first segment is an installed package
      if (exists(`node_modules/${span.split("/")[0]}`)) continue;
      const candidates = [span, path.posix.join(path.posix.dirname(file), span)];
      if (!candidates.some(exists))
        findings.push(finding(file, 0, "H-PATH", `mentions ${span} which does not exist`));
    }
    for (const m of text.matchAll(/\bR-[A-Z]+-\d\d\b/g)) {
      if (definedRules.size > 0 && !definedRules.has(m[0]))
        findings.push(
          finding(file, 0, "H-RULE-REF", `cites ${m[0]} which is not defined in docs/engineering`),
        );
    }
    for (const m of text.matchAll(/\bG-\d\d\b/g)) {
      if (definedGates.size > 0 && !definedGates.has(m[0]))
        findings.push(
          finding(
            file,
            0,
            "H-GATE-REF",
            `cites ${m[0]} which is not defined in docs/engineering/quality-gates.md`,
          ),
        );
    }
  }

  // --- skills
  for (const file of files.filter((f) => /^\.claude\/skills\/[^/]+\/SKILL\.md$/.test(f))) {
    const text = readText(root, file) ?? "";
    const front = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? "";
    const dir = file.split("/")[2];
    const name = /^name:\s*(\S+)/m.exec(front)?.[1];
    if (name !== dir)
      findings.push(finding(file, 0, "H-SKILL", `name must equal the folder name (${dir})`));
    if (!/^description:\s*\S/m.test(front))
      findings.push(finding(file, 0, "H-SKILL", "needs a description"));
    if (!/^disable-model-invocation:\s*true\s*$/m.test(front))
      findings.push(
        finding(
          file,
          0,
          "H-SKILL",
          "needs disable-model-invocation: true; skills run only when you type the command (HD-02)",
        ),
      );
  }

  // --- ADRs
  const adrFiles = files.filter(
    (f) => /^docs\/adr\/[^/]+\.md$/.test(f) && !/\/(_template|README)\.md$/.test(f),
  );
  const numbers = new Map();
  for (const file of adrFiles) {
    const base = path.posix.basename(file);
    const number = /^(\d{3})-[a-z0-9-]+\.md$/.exec(base)?.[1];
    if (!number) {
      findings.push(finding(file, 0, "H-ADR", "ADR file names look like 001-short-title.md"));
      continue;
    }
    if (numbers.has(number))
      findings.push(
        finding(file, 0, "H-ADR", `ADR number ${number} is also used by ${numbers.get(number)}`),
      );
    numbers.set(number, file);
    const text = readText(root, file) ?? "";
    if (!/^- Status:\s*(Proposed|Accepted|Superseded by ADR-\d{3})\b/m.test(text))
      findings.push(
        finding(
          file,
          0,
          "H-ADR",
          "needs a line '- Status: Proposed' (or Accepted, or Superseded by ADR-NNN)",
        ),
      );
  }

  // --- Claude Code adapter
  if (exists(".claude/settings.json")) {
    let settings = null;
    try {
      settings = JSON.parse(fs.readFileSync(path.join(root, ".claude/settings.json"), "utf8"));
    } catch {
      findings.push(
        finding(
          ".claude/settings.json",
          0,
          "H-SETTINGS",
          "is not valid JSON (comments and trailing commas are errors)",
        ),
      );
    }
    const hookCommands = JSON.stringify(settings?.hooks ?? {});
    for (const m of hookCommands.matchAll(/\.claude\/hooks\/([\w-]+\.mjs)/g)) {
      const rel = `.claude/hooks/${m[1]}`;
      if (!exists(rel))
        findings.push(
          finding(".claude/settings.json", 0, "H-HOOK", `hook script ${rel} does not exist`),
        );
      else if (!files.some((f) => /\.test\.mjs$/.test(f) && f.includes(path.basename(rel, ".mjs"))))
        findings.push(
          finding(rel, 0, "H-HOOK", "hook scripts need a test file (scripts/__tests__)"),
        );
    }
  }
  if (exists(".mcp.json")) {
    const text = fs.readFileSync(path.join(root, ".mcp.json"), "utf8");
    if (/@latest\b/.test(text))
      findings.push(
        finding(
          ".mcp.json",
          0,
          "H-MCP",
          "pin MCP servers to an exact version, not @latest (docs/engineering/security.md)",
        ),
      );
  }
  if (
    exists("CLAUDE.md") &&
    fs.readFileSync(path.join(root, "CLAUDE.md"), "utf8").trim() !== "@AGENTS.md"
  ) {
    findings.push(finding("CLAUDE.md", 0, "H-CLAUDE", "CLAUDE.md may only contain @AGENTS.md"));
  }
  if (exists("lefthook.yml")) {
    const text = fs.readFileSync(path.join(root, "lefthook.yml"), "utf8");
    for (const m of text.matchAll(/node (scripts\/[\w./-]+\.mjs)/g)) {
      if (!exists(m[1]))
        findings.push(
          finding("lefthook.yml", 0, "H-LEFTHOOK", `runs ${m[1]} which does not exist`),
        );
    }
  }
  return findings;
}

if (isMain(import.meta.url)) process.exit(printFindings("check-harness", checkHarness()));
